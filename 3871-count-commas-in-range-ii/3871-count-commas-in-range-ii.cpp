class Solution {

#define ll long long

public:
    long long countCommas(long long n) {
        long long ans = 0;

        if (n <= 999)
            return 0;

        if (n >= 1000 && n <= 999999) {

            ans = (n - 1000 + 1);

        } 
        else if (n >= 1000000 && n <= 9999999) {

            ans = (999999 - 1000 + 1) +
                  ((n - 1000000 + 1) * 2);

        } 
        else if (n >= 10000000 && n <= 999999999) {

            ans = (999999 - 1000 + 1) +
                  ((9999999 - 1000000 + 1) * 2) +
                  ((n - 10000000 + 1) * 2);

        } 
        else if (n >= 1000000000 && n <= 999999999999) {

            ans = (999999 - 1000 + 1) +
                  ((9999999 - 1000000 + 1) * 2) +
                  ((999999999 - 10000000 + 1) * 2) +
                  ((n - 1000000000 + 1) * 3);

        } 
        else if (n >= 1000000000000 && n <= 999999999999999) {

            ans = (999999 - 1000 + 1) +
                  ((9999999 - 1000000 + 1) * 2) +
                  ((999999999 - 10000000 + 1) * 2) +
                  ((999999999999 - 1000000000 + 1) * 3) +
                  ((n - 1000000000000 + 1) * 4);

        }
        else if (n == 1000000000000000LL) {

            ans = (999999 - 1000 + 1) +
                  ((9999999 - 1000000 + 1) * 2) +
                  ((999999999 - 10000000 + 1) * 2) +
                  ((999999999999 - 1000000000 + 1) * 3) +
                  ((999999999999999 - 1000000000000 + 1) * 4) +
                  5;
        }

        return ans;
    }
};